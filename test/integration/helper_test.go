func cleanTestTables(t *testing.T, pool *pgxpool.Pool) {
	t.Helper()
	ctx := context.Background()
	tables := []string{
		"planned_order_demands",
		"planned_orders",
		"mrp_demands",
		"mrp_runs",
		"stock_summary",
		"purchase_order_items",
		"purchase_orders",
		"bom_operations",
		"bom_items",
		"bom_versions",
		"bom_headers",
		"product_variants",
	}
	for _, table := range tables {
		_, _ = pool.Exec(ctx, fmt.Sprintf("TRUNCATE TABLE %s.%s CASCADE;", TestTenantSchema, table))
	}
}

func createTestMrpRun(t *testing.T, pool *pgxpool.Pool, planFrom, planTo time.Time) int64 {
	t.Helper()
	var runID int64
	err := pool.QueryRow(context.Background(),
		fmt.Sprintf(`INSERT INTO %s.mrp_runs (plan_from, plan_to, status, triggered_by)
		 VALUES ($1, $2, 'pending', 1) RETURNING id`, TestTenantSchema),
		planFrom, planTo,
	).Scan(&runID)
	if err != nil {
		t.Fatalf("failed to insert test mrp_run: %v", err)
	}
	return runID
}
